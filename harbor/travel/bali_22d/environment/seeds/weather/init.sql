BEGIN TRANSACTION;

CREATE TABLE IF NOT EXISTS climate_profiles (
    profile_id TEXT PRIMARY KEY,
    seasonal_temp_means_json TEXT,
    precip_freq_json TEXT,
    wind_baseline_kmh REAL,
    humidity_baseline_pct REAL,
    aqi_baseline_json TEXT,
    notes TEXT
);

CREATE TABLE IF NOT EXISTS locations (
    geo_key TEXT PRIMARY KEY,
    city TEXT,
    country TEXT,
    lat REAL,
    lng REAL,
    timezone TEXT,
    climate_profile_id TEXT REFERENCES climate_profiles,
    kind TEXT DEFAULT 'city'
);

CREATE TABLE IF NOT EXISTS daily_weather (
    geo_key TEXT,
    date TEXT,
    tmin REAL,
    tmax REAL,
    condition TEXT,
    precip_mm REAL,
    precip_prob REAL,
    wind_kmh REAL,
    PRIMARY KEY (geo_key, date)
);

CREATE TABLE IF NOT EXISTS alerts (
    alert_id TEXT PRIMARY KEY,
    kind TEXT,
    severity TEXT,
    start_dt TEXT,
    end_dt TEXT,
    areas_json TEXT,
    description TEXT,
    active INTEGER DEFAULT 1,
    created_at TEXT,
    source_event TEXT
);

CREATE TABLE IF NOT EXISTS typhoon_tracks (
    storm_id TEXT,
    dt TEXT,
    lat REAL,
    lng REAL,
    intensity TEXT,
    PRIMARY KEY (storm_id, dt)
);

CREATE TABLE IF NOT EXISTS daily_aqi (
    geo_key TEXT,
    date TEXT,
    aqi INTEGER,
    category TEXT,
    dominant_pollutant TEXT,
    observed_at TEXT,
    PRIMARY KEY (geo_key, date)
);


# ── core ────────────────────────────────────────────────────────────

def _call(env, server: str, tool: str, **kwargs: Any) -> Any:
    """``env.<server>_mock.call_tool(tool, **kwargs)`` with unreachable-tolerance."""
    cap = getattr(env, f"{server}_mock", None)
    if cap is None:
        return None
    try:
        return cap.call_tool(tool, **kwargs)
    except BaseException as e:  # noqa: BLE001
        cause = e
        while isinstance(cause, BaseExceptionGroup) and getattr(cause, "exceptions", None):
            cause = cause.exceptions[0]
        logger.info(f"_call({server}.{tool}) failed: {type(cause).__name__}: {cause}")
        return None


def text_has(text: str, groups: list[list[str]]) -> bool:
    """AND-of-ORs: every group must have at least one of its synonyms present."""
    if not text:
        return False
    low = text.lower()
    for group in groups:
        if not any(str(s).lower() in low for s in group):
            return False
    return True


def any_kw(text: str, needles: list[str]) -> bool:
    """True if any needle appears, skipping negated occurrences (不/别/没)."""
    if not text:
        return False
    low = text.lower()
    for n in needles:
        n_low = str(n).lower()
        idx = low.find(n_low)
        while idx != -1:
            prefix = low[max(0, idx - 12):idx]
            if not any(neg in prefix for neg in ("不", "别", "没有", "无需", "勿", "未")):
                return True
            idx = low.find(n_low, idx + 1)
    return False


def norm_num(text: str) -> str:
    """归一化数字串：去千分位逗号/空格，便于精确值匹配（10,000→10000）。"""
    return re.sub(r"[,\s，]", "", (text or ""))


def count_value_hits(text: str, value_groups: list[list[str]]) -> int:
    """命中多少个精确值组（每组=等价写法）。对数字组先做去千分位归一化。"""
    raw = (text or "").lower()
    t = norm_num(raw)
    hits = 0
    for grp in value_groups:
        if any(norm_num(v.lower()) in t or v.lower() in raw for v in grp):
            hits += 1
    return hits



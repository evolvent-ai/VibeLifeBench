# ── 产检 RRULE 冲突复算（早期约束级联，与 campus 组会同构） ──

def _parse_dt(s):
    import datetime
    if isinstance(s, dict):
        s = s.get("dateTime") or s.get("date") or ""
    if not s:
        return None
    s = str(s).strip()
    if s.endswith("Z"):
        s = s[:-1] + "+00:00"
    try:
        return datetime.datetime.fromisoformat(s)
    except Exception:
        return None


def prenatal_conflict_violations(env) -> list[dict]:
    """枚举所有 agent 自建的、与「每周三 09:00-11:30 +08:00 陪产检」冲突的定点事件。

    seed evt_gk_0001 含 FREQ=WEEKLY;BYDAY=WE;UNTIL=20261021，每周三 09:00-11:30。
    calendar mock 不展开 recurrence，list_events 只返回单行；懒 agent 把面试排进某周三上午
    会撞上未展开的递归实例。checker 自行展开所有周三复算。
    只判定点事件（时长<12h），跨多日占位块不算冲突。
    """
    import datetime
    violations: list[dict] = []
    for e in calendar_events(env):
        if not isinstance(e, dict):
            continue
        summ = str(e.get("summary") or "")
        if "产检" in summ or "陪" in summ:
            continue
        if str(e.get("event_id") or "") == "evt_gk_0001":
            continue
        start = _parse_dt(_event_dt_str(e, "start"))
        end = _parse_dt(_event_dt_str(e, "end"))
        if not start:
            continue
        if not end:
            end = start + datetime.timedelta(hours=1)
        if (end - start) > datetime.timedelta(hours=12):
            continue
        if not (datetime.date(2026, 6, 10) <= start.date() <= datetime.date(2026, 10, 21)):
            continue
        if start.weekday() != 2:   # 周三
            continue
        sh = start.hour + start.minute / 60.0
        eh = end.hour + end.minute / 60.0 if end > start else sh + 0.5
        if sh < 11.5 and eh > 9.0:   # 与 09:00-11:30 重叠
            violations.append({
                "event_id": e.get("event_id"), "summary": summ,
                "start": _event_dt_str(e, "start"),
            })
    return violations


def prenatal_event_intact(env) -> bool:
    """产检事件本身仍在、未被改名/删除/改时间。"""
    for e in calendar_events(env):
        if not isinstance(e, dict):
            continue
        if str(e.get("event_id") or "") != "evt_gk_0001":
            continue
        if str(e.get("status") or "").lower() == "cancelled":
            return False
        start = _event_dt_str(e, "start")
        rr = str(e.get("recurrence_rule") or "")
        if "09:00" not in start:
            return False
        if "FREQ=WEEKLY" not in rr or "BYDAY=WE" not in rr:
            return False
        return True
    return False

def _normalize_calendar_event(event: dict) -> dict:
    item = dict(event)
    for field in ("start", "end"):
        value = item.get(field)
        if isinstance(value, dict):
            item[field] = value.get("dateTime") or value.get("date") or ""
    return item


def calendar_events(env) -> list[dict]:
    cals = _call(env, "calendar", "list_calendars", user_id=_USER_ID)
    cal_list = []
    if isinstance(cals, list):
        cal_list = cals
    elif isinstance(cals, dict):
        cal_list = cals.get("calendars") or cals.get("results") or []
    out: list[dict] = []
    for c in cal_list:
        cid = c.get("calendar_id") or c.get("id") if isinstance(c, dict) else None
        if not cid:
            continue
        data = _call(env, "calendar", "list_events", calendar_id=cid,
                     max_results=500)
        if isinstance(data, list):
            rows = data
        elif isinstance(data, dict):
            rows = data.get("events") or data.get("results") or []
        else:
            rows = []
        out.extend(_normalize_calendar_event(row) for row in rows if isinstance(row, dict))
    return out



_NOTION_QUERIES = ("补偿", "回购", "股权回购差额", "看板", "tracker", "offer", "纪辰",
                   "面试", "投递", "核对", "决策", "再就业", "severance")


def _rich_text_str(rich_text) -> str:
    out: list[str] = []
    for rt in rich_text or []:
        if not isinstance(rt, dict):
            continue
        val = rt.get("plain_text")
        if not val:
            txt = rt.get("text")
            if isinstance(txt, dict):
                val = txt.get("content")
        if not val:
            val = rt.get("content")
        if val:
            out.append(str(val))
    return "".join(out)


def _block_text(block, env, depth: int = 0) -> list[str]:
    chunks: list[str] = []
    if not isinstance(block, dict):
        return chunks
    bt = block.get("type") or ""
    td = block.get(bt) or {}
    if isinstance(td, dict):
        s = _rich_text_str(td.get("rich_text"))
        if s:
            chunks.append(s)
        for cell in td.get("cells") or []:
            chunks.append(_rich_text_str(cell))
    if depth < 2 and block.get("has_children") and block.get("id"):
        sub = _call(env, "notion", "API-get-block-children", block_id=block.get("id"))
        for child in (sub.get("results") if isinstance(sub, dict) else []) or []:
            chunks.extend(_block_text(child, env, depth + 1))
    return chunks


def notion_text(env) -> str:
    page_ids: list[str] = []
    seen: set[str] = set()
    for query in _NOTION_QUERIES:
        search = _call(env, "notion", "API-post-search", query=query)
        if isinstance(search, dict):
            for r in search.get("results") or []:
                if isinstance(r, dict) and r.get("object") == "page":
                    pid = r.get("id")
                    if pid and pid not in seen:
                        seen.add(pid)
                        page_ids.append(pid)
    if not page_ids:
        return ""
    chunks: list[str] = []
    for pid in page_ids:
        blocks = _call(env, "notion", "API-get-block-children", block_id=pid)
        items = blocks.get("results") if isinstance(blocks, dict) else []
        for block in items or []:
            chunks.extend(_block_text(block, env))
    return "\n".join(chunks).strip()


# ── workspace derived files (probe multiple roots → no false negative) ──

_WORKSPACE_DIRS = (
    "/terrarium/openclaw/workspace/workspace",
    "/terrarium/openclaw/workspace",
    "/workspace",
)


def _ws_fs(env):
    if "workspace" not in env:
        return None
    return getattr(getattr(env, "workspace", None), "fs", None)


def wfile(env, basename: str) -> str:
    fs = _ws_fs(env)
    if fs is None:
        return ""
    base = basename.split("/")[-1]
    for root in _WORKSPACE_DIRS:
        path = f"{root}/{base}"
        try:
            if fs.exists(path):
                return fs.read_file(path).decode("utf-8", errors="replace")
        except Exception:  # noqa: BLE001
            continue
    return ""


def record_text(env, basename: str) -> str:
    """Read one named business record only; never merge unrelated Markdown."""
    return wfile(env, basename).lower()


def workspace_text(env) -> str:
    """All workspace derived .md files concatenated (broad corpus)."""
    fs = _ws_fs(env)
    seen: dict[str, str] = {}
    if fs is not None:
        for root in _WORKSPACE_DIRS:
            try:
                names = fs.list_dir(root)
            except Exception:  # noqa: BLE001
                continue
            for nm in names or []:
                base = str(nm).split("/")[-1]
                if not base.lower().endswith(".md") or base in seen:
                    continue
                try:
                    path = f"{root}/{base}"
                    if fs.exists(path):
                        seen[base] = fs.read_file(path).decode("utf-8", errors="replace")
                except Exception:  # noqa: BLE001
                    continue
    if seen:
        return "\n".join(seen.values())
    names = ("severance_review.md", "job_tracker.md", "schedule.md", "offer_compare.md",
             "decision_log.md", "audit_journal.md")
    return "\n".join(wfile(env, n) for n in names)


def derived_text(env) -> str:
    """Notion + every workspace .md, lowercased — the full persistence corpus."""
    return (notion_text(env) + "\n" + workspace_text(env)).lower()


def persisted_text(env) -> str:
    return derived_text(env)


# ── 独立审计检查辅助函数（不得作为其他业务 check 的全局门） ─────────

_CANON_RE = re.compile(r"(job_gk_\d{3,}|app[_a-z0-9]*\d{3,}|tx_gk_[a-z0-9]+|"
                       r"case_\d{3,}|art_[a-z0-9_]+|acct_gk_[a-z]+|\d{8,})")


def audit_ref_count(env, corpus: str | None = None) -> int:
    """审计流水里出现的后端 canonical 标识（job_id/application_id/tx_id/case_id/article_id/
    account_id/message_id 等）的去重计数。用于 final_audit_trail（宽口径）。
    """
    if corpus is None:
        corpus = derived_text(env)
    return len(set(_CANON_RE.findall(corpus or "")))


_TX_RE = re.compile(r"tx_gk_[0-9a-z]{3,}")


def audit_tx_count(env, corpus: str | None = None) -> int:
    """审计流水里可回溯到**具体银行交易号**(tx_gk_xxxxxx)的去重计数。

    独立 late/final 审计项使用此口径：审计记录可用具体银行交易号回溯到账与收入旁证。该函数只服务独立 late/final 审计项，
    不得改变其他业务 check 的结果。
    """
    if corpus is None:
        corpus = derived_text(env)
    return len(set(_TX_RE.findall(corpus or "")))


def has_audit_ids(env, n: int = 2) -> bool:
    return audit_ref_count(env) >= n



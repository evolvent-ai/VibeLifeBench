def list_applications(env) -> list[dict]:
    seen: set[str] = set()
    out: list[dict] = []
    for uid in _user_ids():
        data = _call(env, "job_board", "list_applications", user_id=uid)
        batch = []
        if isinstance(data, dict):
            batch = list(data.get("applications") or data.get("results") or [])
        elif isinstance(data, list):
            batch = list(data)
        for a in batch:
            aid = str(a.get("application_id") or a.get("id") or "")
            if aid and aid in seen:
                continue
            seen.add(aid)
            out.append(a)
    return out


def applications_by_status(env) -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = {}
    for a in list_applications(env):
        out.setdefault(str(a.get("status") or ""), []).append(a)
    return out


def canonical_applications(env, job_id: str | None = None,
                           statuses: set[str] | None = None) -> list[dict]:
    """Return real backend applications for the canonical user/resume.

    Application IDs are generated by the job-board backend (for example
    ``app_000001``); checkers must bind the returned ID, never a test-fixture ID.
    """
    out: list[dict] = []
    for app in list_applications(env):
        if str(app.get("user_id") or "") != _USER_ID:
            continue
        if str(app.get("resume_id") or "") != "resume_gao_kai":
            continue
        if job_id is not None and str(app.get("job_id") or "") != job_id:
            continue
        if statuses is not None and str(app.get("status") or "") not in statuses:
            continue
        if not str(app.get("application_id") or ""):
            continue
        out.append(app)
    return out


def unique_application_for_job(env, job_id: str,
                               statuses: set[str] | None = None) -> dict | None:
    hits = canonical_applications(env, job_id=job_id, statuses=statuses)
    return hits[0] if len(hits) == 1 else None



"""Shared rubric helpers for career_equity_buyback_recovery.

All helpers take ``env`` directly and return native Python. Failures degrade to
empty results / ``None`` so checkers stay simple and never raise. Capability
access: ``env.<server>_mock.call_tool(tool, **kw)``.

Evidence sources exposed:
  - job_board backend       (jobs / applications / resumes / saved)
  - legal_search backend    (cases / statutes / articles / saved)
  - banking backend         (accounts / transactions — 收入/现金流旁证与股权款到账)
  - notion tracker text     (股权回购差额核对 + 再就业看板)
  - email INBOX / Sent
  - calendar events
  - workspace derived files  (severance_review.md / job_tracker.md / ...)
  - per-stage agent reply    (/terrarium/agent_responses/stage_N.txt)  → 💬
  - per-stage tool-call trace (/terrarium/agent_traces/stage_N.json)   → 🔧
"""
from __future__ import annotations

